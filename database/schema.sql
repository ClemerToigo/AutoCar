CREATE TABLE IF NOT EXISTS veiculos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  marca_id INTEGER NOT NULL REFERENCES marcas(id) ON DELETE RESTRICT,
  categoria_id INTEGER NOT NULL REFERENCES categorias(id) ON DELETE RESTRICT,
  modelo VARCHAR(120) NOT NULL,
  ano INTEGER NOT NULL CHECK (ano BETWEEN 1886 AND 2200),
  quilometragem INTEGER NOT NULL CHECK (quilometragem >= 0),
  preco NUMERIC(12,2) NOT NULL CHECK (preco > 0),
  combustivel VARCHAR(20) NOT NULL,
  cambio VARCHAR(20) NOT NULL,
  cor VARCHAR(80) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'DISPONIVEL' CHECK (status IN ('DISPONIVEL', 'RESERVADO', 'VENDIDO')),
  descricao TEXT NOT NULL DEFAULT '',
  foto VARCHAR(255),
  galeria JSONB NOT NULL DEFAULT '[]',
  versao INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS veiculos_marca_idx ON veiculos(marca_id);
CREATE INDEX IF NOT EXISTS veiculos_categoria_idx ON veiculos(categoria_id);

-- Serviços e vendas (CRUDs de Serviços e Vendas). Estrutura aditiva: não remove tabelas nem dados existentes.
CREATE TABLE IF NOT EXISTS servicos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  descricao TEXT NOT NULL DEFAULT '',
  preco NUMERIC(12,2) NOT NULL CHECK (preco >= 0),
  ativo BOOLEAN NOT NULL DEFAULT TRUE,
  versao INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS servicos_nome_unique ON servicos (lower(nome));
CREATE TABLE IF NOT EXISTS vendas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
  veiculo_id INTEGER NOT NULL REFERENCES veiculos(id) ON DELETE RESTRICT,
  valor_veiculo NUMERIC(12,2) NOT NULL CHECK (valor_veiculo > 0),
  valor_servicos NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (valor_servicos >= 0),
  valor_total NUMERIC(12,2) NOT NULL CHECK (valor_total > 0),
  forma_pagamento VARCHAR(20) NOT NULL CHECK (forma_pagamento IN ('A_VISTA', 'FINANCIAMENTO', 'CARTAO')),
  status VARCHAR(20) NOT NULL DEFAULT 'EM_NEGOCIACAO' CHECK (status IN ('EM_NEGOCIACAO', 'APROVADA', 'CONCLUIDA', 'CANCELADA')),
  versao INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS vendas_cliente_idx ON vendas(cliente_id);
CREATE INDEX IF NOT EXISTS vendas_veiculo_idx ON vendas(veiculo_id);
-- Um veículo só pode ter uma venda não cancelada por vez.
CREATE UNIQUE INDEX IF NOT EXISTS vendas_veiculo_ativa_unique ON vendas (veiculo_id) WHERE status <> 'CANCELADA';
-- Serviços adicionais de cada venda; o preço é uma cópia do valor cobrado na época da venda.
CREATE TABLE IF NOT EXISTS venda_servicos (
  venda_id INTEGER NOT NULL REFERENCES vendas(id) ON DELETE CASCADE,
  servico_id INTEGER NOT NULL REFERENCES servicos(id) ON DELETE RESTRICT,
  preco NUMERIC(12,2) NOT NULL CHECK (preco >= 0),
  PRIMARY KEY (venda_id, servico_id)
);
CREATE INDEX IF NOT EXISTS venda_servicos_servico_idx ON venda_servicos(servico_id);
