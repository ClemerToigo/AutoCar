CREATE TABLE IF NOT EXISTS marcas (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome VARCHAR(100) NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS categorias (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome VARCHAR(100) NOT NULL UNIQUE);
