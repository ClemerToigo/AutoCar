CREATE TABLE IF NOT EXISTS veiculos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  marca_id INTEGER NOT NULL REFERENCES marcas(id) ON DELETE RESTRICT,
  categoria_id INTEGER NOT NULL REFERENCES categorias(id) ON DELETE RESTRICT,
  modelo VARCHAR(120) NOT NULL,
  ano INTEGER NOT NULL CHECK (ano BETWEEN 1886 AND 2200),
  quilometragem INTEGER NOT NULL CHECK (quilometragem >= 0),
  preco NUMERIC(12,2) NOT NULL CHECK (preco > 0),
  combustivel VARCHAR(20) NOT NULL,
  cambio VARCHAR(20) NOT NULL,
  cor VARCHAR(80) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'DISPONIVEL' CHECK (status IN ('DISPONIVEL', 'RESERVADO', 'VENDIDO')),
  descricao TEXT NOT NULL DEFAULT '',
  foto VARCHAR(255),
  galeria JSONB NOT NULL DEFAULT '[]',
  versao INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS veiculos_marca_idx ON veiculos(marca_id);
CREATE INDEX IF NOT EXISTS veiculos_categoria_idx ON veiculos(categoria_id);
